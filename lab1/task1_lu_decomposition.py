def LU_decompose(A, logger=None):
    """LU-разложение с выбором главного элемента (как в методичке)
    
    Алгоритм:
    1. Применяем метод Гаусса к матрице A, получаем верхнюю треугольную U
    2. Множители μ(k)ij запоминаем в нижнюю треугольную матрицу L
    3. В результате: A = L × U (с учетом перестановок P)
    """
    # n - размерность матрицы (количество строк/столбцов)
    n = len(A)
    
    # A_k - рабочая матрица, которую будем преобразовывать
    # Создаем глубокую копию исходной матрицы A, чтобы не изменять оригинал
    # [row[:] for row in A] - копируем каждую строку отдельно
    A_k = [row[:] for row in A]
    
    # L - нижняя треугольная матрица (Lower triangular)
    # Инициализируем нулями размером n×n
    L = [[0.0 for _ in range(n)] for _ in range(n)]
    # Заполняем диагональ единицами (по определению L-матрицы)
    for i in range(n):
        L[i][i] = 1.0
    
    # P - вектор перестановок строк (изначально [0, 1, 2, ..., n-1])
    # P[i] показывает, какая исходная строка находится на позиции i
    P = list(range(n))
    # swaps - счетчик количества перестановок (нужен для вычисления определителя)
    swaps = 0
    
    if logger:
        logger.log_matrix("Исходная матрица A(0)", A_k)
        logger.log_iteration(0, {
            "Этап": "Начало метода Гаусса",
            "Цель": "Привести A к верхней треугольной матрице U",
            "Попутно": "Запоминать множители в матрицу L"
        })
    
    # Прямой ход метода Гаусса (делаем n-1 шагов, т.к. последняя строка уже будет готова)
    for k in range(n - 1):
        if logger:
            logger.log_iteration(k + 0.05, {
                f"=== ШАГ {k + 1} МЕТОДА ГАУССА ===": f"Обнуляем столбец {k} под диагональю",
                "Текущая матрица A(k)": [row[:] for row in A_k]
            })
        
        # ШАГ 1: Выбор главного элемента в столбце k (для численной устойчивости)
        # Ищем строку с максимальным по модулю элементом в столбце k
        max_row = k  # Изначально считаем, что максимум на текущей строке
        max_val = abs(A_k[k][k])  # Значение элемента на диагонали
        
        # Проходим по всем строкам ниже текущей
        for i in range(k + 1, n):
            # Если нашли элемент больше по модулю
            if abs(A_k[i][k]) > max_val:
                max_val = abs(A_k[i][k])  # Обновляем максимум
                max_row = i  # Запоминаем номер строки с максимумом
        
        # ШАГ 2: Перестановка строк (если максимальный элемент не на текущей строке)
        if max_row != k:
            # Меняем местами строки k и max_row в матрице A_k
            A_k[k], A_k[max_row] = A_k[max_row], A_k[k]
            # Обновляем вектор перестановок
            P[k], P[max_row] = P[max_row], P[k]
            
            # Меняем уже вычисленные элементы L (только левую часть до столбца k)
            for j in range(k):
                L[k][j], L[max_row][j] = L[max_row][j], L[k][j]
            
            # Увеличиваем счетчик перестановок (влияет на знак определителя)
            swaps += 1
            
            if logger:
                logger.log_iteration(k + 0.1, {
                    "Выбор главного элемента": f"a({k},{k}) = {max_val:.4f}",
                    "Перестановка": f"Строка {k} ↔ Строка {max_row}",
                    "Матрица после перестановки": [row[:] for row in A_k]
                })
        
        # ШАГ 3: Проверка на вырожденность (диагональный элемент не должен быть нулем)
        # Если элемент слишком мал (практически ноль), матрица вырождена
        if abs(A_k[k][k]) < 1e-10:
            raise ValueError(f"Матрица вырождена на шаге {k}")
        
        # ШАГ 4: Вычисление множителей μ(k)ij и обнуление элементов под диагональю
        multipliers = {}  # Словарь для логирования множителей
        
        # Проходим по всем строкам ниже текущей (k+1, k+2, ..., n-1)
        for i in range(k + 1, n):
            # Вычисляем множитель μ(k)ij = a(k)ik / a(k)kk
            # Это число, на которое нужно умножить строку k, чтобы вычесть из строки i
            mu = A_k[i][k] / A_k[k][k]
            # Сохраняем множитель в матрицу L (это и есть LU-разложение!)
            L[i][k] = mu
            multipliers[f"μ({k+1}){i+1}{k+1}"] = mu  # Для логирования
            
            # Вычитаем: строка_i = строка_i - μ × строка_k
            # Это обнуляет элемент A_k[i][k] и преобразует остальные элементы строки
            for j in range(k, n):
                A_k[i][j] = A_k[i][j] - mu * A_k[k][j]
        
        if logger:
            logger.log_iteration(k + 1, {
                f"Множители на шаге {k + 1}": multipliers,
                "Формула": f"строка_i = строка_i - μ(k)_ik × строка_{k}",
                f"Матрица A({k + 1}) после обнуления": [row[:] for row in A_k],
                "Текущая матрица L": [row[:] for row in L]
            })
    
    # A_k теперь содержит верхнюю треугольную матрицу U
    U = A_k
    
    if logger:
        logger.log_iteration(n, {
            "=== ПРЯМОЙ ХОД ЗАВЕРШЕН ===": "Получена верхняя треугольная матрица U",
            "Финальная матрица U": U,
            "Финальная матрица L": L,
            "Проверка": "L × U должно дать исходную A (с учетом перестановок)"
        })
    
    return L, U, P, swaps


def solve_system(L, U, b, P, logger=None):
    """Решение системы LUx = Pb через прямой и обратный ход
    
    Идея: Ax = b преобразуется в LUx = Pb
    Решаем в два этапа:
    1. Ly = Pb (прямой ход)
    2. Ux = y (обратный ход)
    """
    # n - размерность системы
    n = len(L)
    
    # Применяем перестановки к вектору b
    # P[i] показывает, какой элемент исходного b должен быть на позиции i
    Pb = [b[P[i]] for i in range(n)]
    
    if logger:
        logger.log_iteration(0, {
            "Этап": "Применение перестановок к вектору b",
            "Исходный b": b,
            "Вектор перестановок P": P,
            "Pb после перестановок": Pb
        })
    
    # Прямой ход: Ly = Pb
    # Решаем систему с нижней треугольной матрицей L
    y = [0 for _ in range(n)]  # Вектор решения прямого хода
    
    if logger:
        logger.log_iteration(0.5, {
            "Этап": "Прямой ход (Ly = Pb)",
            "Матрица L": L,
            "Вектор Pb": Pb
        })

    # Идем сверху вниз (от i=0 до i=n-1)
    for i in range(n):
        # s - сумма уже известных элементов: L[i][0]*y[0] + L[i][1]*y[1] + ... + L[i][i-1]*y[i-1]
        s = 0
        for j in range(i):  # Суммируем только элементы слева от диагонали
            s += L[i][j] * y[j]
        # Из уравнения L[i][i]*y[i] + s = Pb[i] выражаем y[i]
        y[i] = (Pb[i] - s) / L[i][i]
        
        if logger:
            logger.log_iteration(i + 1, {
                "Прямой ход - шаг": i + 1,
                f"y[{i}]": y[i],
                "Сумма s": s,
                "Формула": f"({Pb[i]} - {s}) / {L[i][i]} = {y[i]}"
            })

    if logger:
        logger.log_iteration(n + 1, {
            "Этап": "Обратный ход (Ux = y)",
            "Матрица U": U,
            "Вектор y": y
        })

    # Обратный ход: Ux = y
    # Решаем систему с верхней треугольной матрицей U
    x = [0 for _ in range(n)]  # Вектор решения (финальный ответ)
    # Идем снизу вверх (от i=n-1 до i=0)
    for i in range(n - 1, -1, -1):
        # s - сумма уже известных элементов: U[i][i+1]*x[i+1] + ... + U[i][n-1]*x[n-1]
        s = 0
        for j in range(i + 1, n):  # Суммируем только элементы справа от диагонали
            s += U[i][j] * x[j]
        # Из уравнения U[i][i]*x[i] + s = y[i] выражаем x[i]
        x[i] = (y[i] - s) / U[i][i]
        
        if logger:
            logger.log_iteration(n + 2 + (n-1-i), {
                "Обратный ход - шаг": n - i,
                f"x[{i}]": x[i],
                "Сумма s": s,
                "Формула": f"({y[i]} - {s}) / {U[i][i]} = {x[i]}"
            })
    
    return x


def determinant(A):
    """Вычисление определителя через LU-разложение с учетом перестановок
    
    Формула: det(A) = det(P) × det(L) × det(U)
    где det(P) = (-1)^swaps, det(L) = 1, det(U) = произведение диагональных элементов
    """
    # Выполняем LU-разложение (нам нужны только U и количество перестановок)
    _, U, P, swaps = LU_decompose(A)
    
    # det(A) = (-1)^swaps × произведение диагональных элементов U
    # Каждая перестановка строк меняет знак определителя
    det = (-1) ** swaps
    # Определитель треугольной матрицы = произведение диагональных элементов
    for i in range(len(U)):
        det *= U[i][i]
    return det


def inverse_matrix(A):
    """Вычисление обратной матрицы
    
    Идея: A × A^(-1) = E (единичная матрица)
    Решаем n систем: A × столбец_i = e_i, где e_i - i-й столбец единичной матрицы
    """
    n = len(A)
    # E - единичная матрица (1 на диагонали, 0 в остальных местах)
    E = [[float(i == j) for i in range(n)] for j in range(n)]
    # Выполняем LU-разложение один раз
    L, U, P, swaps = LU_decompose(A)
    # Для каждого столбца единичной матрицы решаем систему
    A_inv = []
    for e in E:  # e - столбец единичной матрицы
        inv_row = solve_system(L, U, e, P)  # Решаем A × x = e
        A_inv.append(inv_row)  # Добавляем столбец обратной матрицы
    # Транспонируем, т.к. мы собирали по строкам, а нужно по столбцам
    return transpose(A_inv)


def transpose(X):
    """Транспонирование матрицы (строки становятся столбцами и наоборот)"""
    m = len(X)  # Количество строк
    n = len(X[0])  # Количество столбцов
    # Создаем новую матрицу, где X[j][i] становится X^T[i][j]
    transpose_matrix = [[X[j][i] for j in range(n)] for i in range(m)]
    return transpose_matrix


