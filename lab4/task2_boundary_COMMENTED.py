import numpy as np
import matplotlib.pyplot as plt
from typing import Callable, Tuple
from scipy.optimize import fsolve  # Для решения нелинейных уравнений


# ═══════════════════════════════════════════════════════════════════════════
# КЛАСС ДЛЯ РЕШЕНИЯ КРАЕВОЙ ЗАДАЧИ
# ═══════════════════════════════════════════════════════════════════════════

class BoundaryProblemSolver:
    """
    Класс для численного решения краевой задачи для ОДУ 2-го порядка
    
    Краевая задача:
        y'' = f(x, y, y')
        Граничные условия на концах отрезка [a, b]
    
    Отличие от задачи Коши:
        - В задаче Коши: условия в одной точке (начальные условия)
        - В краевой задаче: условия на двух концах отрезка
    """
    
    def __init__(self, a: float, b: float, h: float):
        """
        Инициализация решателя краевой задачи
        
        Параметры:
            a: левая граница отрезка
            b: правая граница отрезка
            h: шаг сетки
        """
        self.a = a  # Левая граница
        self.b = b  # Правая граница
        self.h = h  # Шаг сетки
        
        # Вычисляем количество узлов сетки
        self.n = int((b - a) / h) + 1
        
        # Создаем массив узлов сетки
        self.x = np.linspace(a, b, self.n)
    
    # ═══════════════════════════════════════════════════════════════════════
    # МЕТОД СТРЕЛЬБЫ (ПРИСТРЕЛКИ)
    # ═══════════════════════════════════════════════════════════════════════
    
    def shooting_method(self, f_system: Callable, bc_left: Tuple, 
                       bc_right: Callable, initial_guess: float = 0.0):
        """
        Метод стрельбы для решения краевой задачи
        
        ИДЕЯ МЕТОДА (аналогия со стрельбой):
            1. Стреляем из точки A (левая граница)
            2. Хотим попасть в точку B (правая граница)
            3. Подбираем угол выстрела (параметр η)
        
        МАТЕМАТИЧЕСКИ:
            1. Заменяем неизвестное граничное условие параметром η
            2. Решаем задачу Коши с этим параметром
            3. Подбираем η так, чтобы выполнялось правое ГУ
        
        АЛГОРИТМ:
            1. Задаем начальное приближение η₀
            2. Решаем задачу Коши, получаем y(b, η₀)
            3. Проверяем правое ГУ: если не выполняется, корректируем η
            4. Повторяем до сходимости
        
        Параметры:
            f_system: правая часть системы ОДУ 1-го порядка
            bc_left: левое граничное условие (тип, значение)
            bc_right: функция проверки правого ГУ
            initial_guess: начальное приближение для η
        """
        
        # ───────────────────────────────────────────────────────────────────
        # ВНУТРЕННЯЯ ФУНКЦИЯ: Решение задачи Коши с параметром η
        # ───────────────────────────────────────────────────────────────────
        def solve_cauchy(eta):
            """
            Решает задачу Коши с параметром eta
            
            Параметр eta - это неизвестное граничное условие,
            которое мы подбираем
            
            Например:
                Если задано y'(a), то y(a) = eta (неизвестно)
                Если задано y(a), то y'(a) = eta (неизвестно)
            """
            
            # Определяем начальные условия в зависимости от типа левого ГУ
            if bc_left[0] == 'derivative':
                # Случай: y'(a) = известно, y(a) = eta (неизвестно)
                y0 = np.array([float(eta), float(bc_left[1])], dtype=float)
            else:
                # Случай: y(a) = известно, y'(a) = eta (неизвестно)
                y0 = np.array([float(bc_left[1]), float(eta)], dtype=float)
            
            # Создаем массив для хранения решения
            y = np.zeros((self.n, 2))
            y[0] = y0  # Устанавливаем начальные условия
            
            # ═══════════════════════════════════════════════════════════════
            # РЕШАЕМ ЗАДАЧУ КОШИ МЕТОДОМ РУНГЕ-КУТТЫ 4
            # ═══════════════════════════════════════════════════════════════
            for i in range(self.n - 1):
                # Стандартный РК4 (см. комментарии в task1)
                k1 = self.h * f_system(self.x[i], y[i])
                k2 = self.h * f_system(self.x[i] + self.h/2, y[i] + k1/2)
                k3 = self.h * f_system(self.x[i] + self.h/2, y[i] + k2/2)
                k4 = self.h * f_system(self.x[i] + self.h, y[i] + k3)
                y[i+1] = y[i] + (k1 + 2*k2 + 2*k3 + k4) / 6
            
            return y
        
        # ───────────────────────────────────────────────────────────────────
        # ВНУТРЕННЯЯ ФУНКЦИЯ: Невязка правого граничного условия
        # ───────────────────────────────────────────────────────────────────
        def residual(eta):
            """
            Вычисляет невязку правого граничного условия
            
            Невязка = 0, когда правое ГУ выполняется
            
            Например, для условия y(b) = y_b:
                residual = y(b, eta) - y_b
            
            Мы ищем такое eta, чтобы residual(eta) = 0
            """
            # Решаем задачу Коши с текущим eta
            y = solve_cauchy(eta)
            
            # Проверяем правое ГУ
            # bc_right - это функция, которая возвращает невязку
            return bc_right(y[-1])  # y[-1] - решение в правой точке
        
        # ───────────────────────────────────────────────────────────────────
        # ПОИСК КОРНЯ УРАВНЕНИЯ residual(eta) = 0
        # ───────────────────────────────────────────────────────────────────
        # Используем функцию fsolve из scipy
        # Она находит корень нелинейного уравнения методом секущих
        eta_solution = fsolve(residual, initial_guess)[0]
        
        # ───────────────────────────────────────────────────────────────────
        # РЕШАЕМ ЗАДАЧУ С НАЙДЕННЫМ ПАРАМЕТРОМ
        # ───────────────────────────────────────────────────────────────────
        y_solution = solve_cauchy(eta_solution)
        
        # Возвращаем сетку и решение (только y, без y')
        return self.x, y_solution[:, 0]
    
    # ═══════════════════════════════════════════════════════════════════════
    # КОНЕЧНО-РАЗНОСТНЫЙ МЕТОД
    # ═══════════════════════════════════════════════════════════════════════
    
    def finite_difference_method(self, p: Callable, q: Callable, f: Callable,
                                bc_left: Tuple, bc_right: Tuple):
        """
        Конечно-разностный метод для уравнения:
            y'' + p(x)y' + q(x)y = f(x)
        
        ИДЕЯ МЕТОДА:
            1. Заменяем производные конечными разностями
            2. Получаем систему линейных алгебраических уравнений
            3. Решаем систему
        
        АППРОКСИМАЦИЯ ПРОИЗВОДНЫХ:
            y'(x_i) ≈ (y_{i+1} - y_{i-1}) / (2h)        - центральная разность
            y''(x_i) ≈ (y_{i+1} - 2y_i + y_{i-1}) / h²  - вторая производная
        
        РЕЗУЛЬТАТ:
            Система Ay = b, где:
            - A - трехдиагональная матрица
            - y - вектор неизвестных значений в узлах
            - b - вектор правых частей
        
        Параметры:
            p, q, f: коэффициенты уравнения
            bc_left, bc_right: граничные условия
        """
        
        n = self.n
        
        # ═══════════════════════════════════════════════════════════════════
        # СОЗДАЕМ МАТРИЦУ СИСТЕМЫ И ВЕКТОР ПРАВЫХ ЧАСТЕЙ
        # ═══════════════════════════════════════════════════════════════════
        A = np.zeros((n, n))  # Матрица коэффициентов
        b = np.zeros(n)       # Вектор правых частей
        
        # ═══════════════════════════════════════════════════════════════════
        # ЛЕВОЕ ГРАНИЧНОЕ УСЛОВИЕ (первая строка системы)
        # ═══════════════════════════════════════════════════════════════════
        if bc_left[0] == 'derivative':
            # Условие: y'(a) = value
            # Аппроксимация односторонней разностью 2-го порядка:
            # y'(a) ≈ (-3y_0 + 4y_1 - y_2) / (2h)
            
            A[0, 0] = -3 / (2*self.h)  # Коэффициент при y_0
            A[0, 1] = 4 / (2*self.h)   # Коэффициент при y_1
            A[0, 2] = -1 / (2*self.h)  # Коэффициент при y_2
            b[0] = bc_left[1]          # Правая часть = заданное значение
            
        elif bc_left[0] == 'mixed':
            # Условие: alpha*y(a) + beta*y'(a) = value
            # Комбинация значения функции и производной
            
            alpha, beta, value = bc_left[1], bc_left[2], bc_left[3]
            A[0, 0] = alpha - 3*beta / (2*self.h)
            A[0, 1] = 4*beta / (2*self.h)
            A[0, 2] = -beta / (2*self.h)
            b[0] = value
            
        else:  # 'value'
            # Условие: y(a) = value
            # Просто: y_0 = value
            
            A[0, 0] = 1
            b[0] = bc_left[1]
        
        # ═══════════════════════════════════════════════════════════════════
        # ВНУТРЕННИЕ ТОЧКИ (строки 1 до n-2)
        # ═══════════════════════════════════════════════════════════════════
        for i in range(1, n-1):
            xi = self.x[i]  # Текущая точка
            
            # Вычисляем коэффициенты уравнения в точке xi
            pi = p(xi)
            qi = q(xi)
            fi = f(xi)
            
            # ───────────────────────────────────────────────────────────────
            # ПОДСТАВЛЯЕМ АППРОКСИМАЦИИ ПРОИЗВОДНЫХ
            # ───────────────────────────────────────────────────────────────
            # Исходное уравнение: y'' + p(x)y' + q(x)y = f(x)
            #
            # Заменяем:
            # y''_i ≈ (y_{i+1} - 2y_i + y_{i-1}) / h²
            # y'_i ≈ (y_{i+1} - y_{i-1}) / (2h)
            #
            # Получаем:
            # (y_{i+1} - 2y_i + y_{i-1})/h² + p_i*(y_{i+1} - y_{i-1})/(2h) + q_i*y_i = f_i
            #
            # Группируем по y_{i-1}, y_i, y_{i+1}:
            
            # Коэффициент при y_{i-1}
            A[i, i-1] = 1/self.h**2 - pi/(2*self.h)
            
            # Коэффициент при y_i
            A[i, i] = -2/self.h**2 + qi
            
            # Коэффициент при y_{i+1}
            A[i, i+1] = 1/self.h**2 + pi/(2*self.h)
            
            # Правая часть
            b[i] = fi
        
        # ═══════════════════════════════════════════════════════════════════
        # ПРАВОЕ ГРАНИЧНОЕ УСЛОВИЕ (последняя строка системы)
        # ═══════════════════════════════════════════════════════════════════
        # Аналогично левому ГУ, но используем правую разность
        
        if bc_right[0] == 'derivative':
            # y'(b) ≈ (y_{n-3} - 4y_{n-2} + 3y_{n-1}) / (2h)
            A[n-1, n-3] = 1 / (2*self.h)
            A[n-1, n-2] = -4 / (2*self.h)
            A[n-1, n-1] = 3 / (2*self.h)
            b[n-1] = bc_right[1]
            
        elif bc_right[0] == 'mixed':
            # alpha*y(b) + beta*y'(b) = value
            alpha, beta, value = bc_right[1], bc_right[2], bc_right[3]
            A[n-1, n-3] = beta / (2*self.h)
            A[n-1, n-2] = -4*beta / (2*self.h)
            A[n-1, n-1] = alpha + 3*beta / (2*self.h)
            b[n-1] = value
            
        else:  # 'value'
            A[n-1, n-1] = 1
            b[n-1] = bc_right[1]
        
        # ═══════════════════════════════════════════════════════════════════
        # РЕШАЕМ СИСТЕМУ ЛИНЕЙНЫХ УРАВНЕНИЙ Ay = b
        # ═══════════════════════════════════════════════════════════════════
        # Используем стандартный решатель из numpy
        # Для трехдиагональных матриц можно использовать метод прогонки
        y = np.linalg.solve(A, b)
        
        return self.x, y


