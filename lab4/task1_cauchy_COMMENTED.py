import numpy as np  # Библиотека для работы с массивами и математическими операциями
import matplotlib.pyplot as plt  # Библиотека для построения графиков
from typing import Callable, Tuple, List  # Типы для аннотаций (улучшают читаемость)


# ═══════════════════════════════════════════════════════════════════════════
# КЛАСС ДЛЯ РЕШЕНИЯ ЗАДАЧИ КОШИ
# ═══════════════════════════════════════════════════════════════════════════

class ODESolver:
    """
    Класс для численного решения задачи Коши для системы ОДУ 1-го порядка
    
    Задача Коши:
        y' = f(x, y)
        y(x0) = y0
    
    где y может быть вектором (система уравнений)
    """
    
    def __init__(self, f: Callable, x0: float, y0: np.ndarray, h: float):
        """
        Инициализация решателя
        
        Параметры:
            f: функция правой части y' = f(x, y)
               Принимает: x (float), y (np.ndarray)
               Возвращает: np.ndarray той же размерности, что и y
            
            x0: начальная точка (float)
                Например, x0 = 1.0
            
            y0: начальные условия (np.ndarray)
                Для системы из n уравнений - массив из n элементов
                Например, [1.0, 1.0] для y(1)=1, y'(1)=1
            
            h: шаг сетки (float)
               Расстояние между соседними точками
               Меньше h → выше точность, но больше вычислений
        """
        self.f = f  # Сохраняем функцию правой части
        self.x0 = x0  # Сохраняем начальную точку
        self.y0 = np.array(y0, dtype=float)  # Преобразуем в numpy массив
        self.h = h  # Сохраняем шаг
    
    # ═══════════════════════════════════════════════════════════════════════
    # МЕТОД ЭЙЛЕРА (1-Й ПОРЯДОК ТОЧНОСТИ)
    # ═══════════════════════════════════════════════════════════════════════
    
    def euler(self, x_end: float) -> Tuple[np.ndarray, np.ndarray]:
        """
        Явный метод Эйлера для решения задачи Коши
        
        Формула: y_{i+1} = y_i + h * f(x_i, y_i)
        
        Геометрическая интерпретация:
            - В каждой точке строим касательную к графику решения
            - Наклон касательной = f(x_i, y_i)
            - Двигаемся вдоль касательной на расстояние h
        
        Параметры:
            x_end: конечная точка интервала
        
        Возвращает:
            x: массив точек сетки [x0, x1, ..., xN]
            y: массив решений в этих точках, размер (N+1) × n
               где n - количество уравнений в системе
        """
        
        # ШАГ 1: Вычисляем количество шагов
        # Формула: N = (x_end - x0) / h
        # +1 потому что включаем обе границы
        n_steps = int((x_end - self.x0) / self.h) + 1
        
        # ШАГ 2: Создаем массив точек x с равномерным шагом
        # linspace создает n_steps точек от x0 до x_end
        x = np.linspace(self.x0, x_end, n_steps)
        
        # ШАГ 3: Создаем массив для хранения решения
        # Размер: n_steps строк × len(y0) столбцов
        # Каждая строка - решение в одной точке x
        # Каждый столбец - одна компонента вектора y
        y = np.zeros((n_steps, len(self.y0)))
        
        # ШАГ 4: Устанавливаем начальные условия
        # В точке x[0] = x0 решение известно: y[0] = y0
        y[0] = self.y0
        
        # ШАГ 5: Основной цикл метода Эйлера
        for i in range(n_steps - 1):
            # Вычисляем производную в текущей точке
            # f(x[i], y[i]) возвращает вектор производных
            derivative = self.f(x[i], y[i])
            
            # Формула Эйлера: следующее значение = текущее + шаг × производная
            # Это линейная экстраполяция вдоль касательной
            y[i+1] = y[i] + self.h * derivative
            
            # ВАЖНО: На каждом шаге накапливается погрешность O(h²)
            # Общая погрешность после N шагов: O(h)
        
        return x, y
    
    # ═══════════════════════════════════════════════════════════════════════
    # МЕТОД РУНГЕ-КУТТЫ 4-ГО ПОРЯДКА
    # ═══════════════════════════════════════════════════════════════════════
    
    def runge_kutta_4(self, x_end: float) -> Tuple[np.ndarray, np.ndarray]:
        """
        Метод Рунге-Кутты 4-го порядка (классический РК4)
        
        Идея метода:
            - Вычисляем наклон (производную) в 4 точках интервала
            - Берем взвешенное среднее этих наклонов
            - Получаем более точное приближение
        
        Формула:
            k1 = h * f(x_i, y_i)
            k2 = h * f(x_i + h/2, y_i + k1/2)
            k3 = h * f(x_i + h/2, y_i + k2/2)
            k4 = h * f(x_i + h, y_i + k3)
            y_{i+1} = y_i + (k1 + 2*k2 + 2*k3 + k4) / 6
        
        Порядок точности: O(h⁴)
        """
        
        # Подготовка (аналогично методу Эйлера)
        n_steps = int((x_end - self.x0) / self.h) + 1
        x = np.linspace(self.x0, x_end, n_steps)
        y = np.zeros((n_steps, len(self.y0)))
        y[0] = self.y0
        
        # Основной цикл РК4
        for i in range(n_steps - 1):
            
            # ═══════════════════════════════════════════════════════════════
            # k1: НАКЛОН В НАЧАЛЕ ИНТЕРВАЛА
            # ═══════════════════════════════════════════════════════════════
            # Вычисляем производную в точке (x_i, y_i)
            # Это известная точка - начало интервала
            k1 = self.h * self.f(x[i], y[i])
            
            # ═══════════════════════════════════════════════════════════════
            # k2: НАКЛОН В СЕРЕДИНЕ ИНТЕРВАЛА (ПЕРВАЯ ОЦЕНКА)
            # ═══════════════════════════════════════════════════════════════
            # Делаем полшага по x: x_i + h/2
            # Делаем полшага по y, используя наклон k1: y_i + k1/2
            # Вычисляем производную в этой промежуточной точке
            k2 = self.h * self.f(x[i] + self.h/2, y[i] + k1/2)
            
            # ═══════════════════════════════════════════════════════════════
            # k3: НАКЛОН В СЕРЕДИНЕ ИНТЕРВАЛА (ВТОРАЯ ОЦЕНКА)
            # ═══════════════════════════════════════════════════════════════
            # Снова полшага по x: x_i + h/2
            # Но теперь используем наклон k2: y_i + k2/2
            # Это улучшенная оценка середины
            k3 = self.h * self.f(x[i] + self.h/2, y[i] + k2/2)
            
            # ═══════════════════════════════════════════════════════════════
            # k4: НАКЛОН В КОНЦЕ ИНТЕРВАЛА
            # ═══════════════════════════════════════════════════════════════
            # Полный шаг по x: x_i + h
            # Используем наклон k3 для прогноза: y_i + k3
            # Вычисляем производную в конечной точке
            k4 = self.h * self.f(x[i] + self.h, y[i] + k3)
            
            # ═══════════════════════════════════════════════════════════════
            # ВЗВЕШЕННОЕ СРЕДНЕЕ ВСЕХ НАКЛОНОВ
            # ═══════════════════════════════════════════════════════════════
            # Веса: 1/6, 2/6, 2/6, 1/6
            # Больший вес для средних точек (k2 и k3)
            # Эти веса обеспечивают 4-й порядок точности
            y[i+1] = y[i] + (k1 + 2*k2 + 2*k3 + k4) / 6
            
            # ВАЖНО: Погрешность на каждом шаге O(h⁵)
            # Общая погрешность: O(h⁴)
        
        return x, y
    
    # ═══════════════════════════════════════════════════════════════════════
    # МЕТОД АДАМСА 4-ГО ПОРЯДКА
    # ═══════════════════════════════════════════════════════════════════════
    
    def adams_4(self, x_end: float) -> Tuple[np.ndarray, np.ndarray]:
        """
        Метод Адамса 4-го порядка (многошаговый метод)
        
        Идея метода:
            - Используем информацию из нескольких предыдущих точек
            - Строим интерполяционный многочлен через эти точки
            - Интегрируем многочлен для получения следующего значения
        
        Формула:
            y_{i+1} = y_i + h/24 * (55*f_i - 59*f_{i-1} + 37*f_{i-2} - 9*f_{i-3})
        
        Особенность:
            - Требует 4 предыдущие точки
            - Нужен "разгон" другим методом (используем РК4)
        
        Преимущество:
            - Требует только 1 вычисление f на шаг (РК4 требует 4)
            - Эффективен для длительных расчетов
        """
        
        # Подготовка
        n_steps = int((x_end - self.x0) / self.h) + 1
        x = np.linspace(self.x0, x_end, n_steps)
        y = np.zeros((n_steps, len(self.y0)))
        y[0] = self.y0
        
        # ═══════════════════════════════════════════════════════════════════
        # РАЗГОН: ПЕРВЫЕ 3 ШАГА МЕТОДОМ РК4
        # ═══════════════════════════════════════════════════════════════════
        # Метод Адамса требует 4 предыдущие точки
        # В начале у нас только 1 точка (начальное условие)
        # Поэтому первые 3 шага делаем методом РК4
        
        for i in range(min(3, n_steps - 1)):
            # Стандартный РК4 (см. комментарии выше)
            k1 = self.h * self.f(x[i], y[i])
            k2 = self.h * self.f(x[i] + self.h/2, y[i] + k1/2)
            k3 = self.h * self.f(x[i] + self.h/2, y[i] + k2/2)
            k4 = self.h * self.f(x[i] + self.h, y[i] + k3)
            y[i+1] = y[i] + (k1 + 2*k2 + 2*k3 + k4) / 6
        
        # ═══════════════════════════════════════════════════════════════════
        # ОСНОВНОЙ ЦИКЛ: МЕТОД АДАМСА
        # ═══════════════════════════════════════════════════════════════════
        # Начинаем с i=3, так как первые 3 точки уже вычислены
        
        for i in range(3, n_steps - 1):
            
            # ───────────────────────────────────────────────────────────────
            # ШАГ 1: Вычисляем значения f в последних 4 точках
            # ───────────────────────────────────────────────────────────────
            # f_vals[0] = f(x_{i-3}, y_{i-3})  - 3 шага назад
            # f_vals[1] = f(x_{i-2}, y_{i-2})  - 2 шага назад
            # f_vals[2] = f(x_{i-1}, y_{i-1})  - 1 шаг назад
            # f_vals[3] = f(x_i, y_i)          - текущая точка
            f_vals = [self.f(x[j], y[j]) for j in range(i-3, i+1)]
            
            # ───────────────────────────────────────────────────────────────
            # ШАГ 2: Формула Адамса 4-го порядка
            # ───────────────────────────────────────────────────────────────
            # Коэффициенты: 55, -59, 37, -9
            # Получены из интегрирования интерполяционного многочлена Лагранжа
            # 
            # Интуиция:
            # - Наибольший вес (55) у текущей точки
            # - Отрицательный вес (-59) у предыдущей для коррекции
            # - Положительные веса (37, -9) для учета истории
            
            y[i+1] = y[i] + self.h/24 * (
                55 * f_vals[3]   # Текущая точка (вес 55)
                - 59 * f_vals[2]  # 1 шаг назад (вес -59)
                + 37 * f_vals[1]  # 2 шага назад (вес 37)
                - 9 * f_vals[0]   # 3 шага назад (вес -9)
            )
            
            # ВАЖНО: Метод использует историю вычислений
            # Это делает его эффективным, но требует разгона
        
        return x, y


# ═══════════════════════════════════════════════════════════════════════════
# ПРЕОБРАЗОВАНИЕ ОДУ 2-ГО ПОРЯДКА В СИСТЕМУ 1-ГО ПОРЯДКА
# ═══════════════════════════════════════════════════════════════════════════

def convert_to_system(x: float, y: np.ndarray) -> np.ndarray:
    """
    Преобразование ОДУ 2-го порядка в систему ОДУ 1-го порядка
    
    Исходное уравнение:
        y'' + 2y' + e^x * y = 0
    
    Преобразование:
        1. Вводим новую переменную: z = y'
        2. Выражаем y'' через z': z' = y''
        3. Из исходного уравнения: y'' = -2y' - e^x * y
        4. Подставляем: z' = -2z - e^x * y
    
    Получаем систему:
        y' = z
        z' = -2z - e^x * y
    
    Параметры:
        x: текущая точка (float)
        y: вектор состояния [y, z] = [y, y']
    
    Возвращает:
        Вектор производных [y', z'] = [z, -2z - e^x * y]
    """
    
    # ───────────────────────────────────────────────────────────────────────
    # Распаковываем вектор состояния
    # ───────────────────────────────────────────────────────────────────────
    y_val = y[0]  # Значение функции y(x)
    z_val = y[1]  # Значение производной y'(x) = z(x)
    
    # ───────────────────────────────────────────────────────────────────────
    # Вычисляем правые части системы
    # ───────────────────────────────────────────────────────────────────────
    y_prime = z_val  # y' = z (по определению z)
    z_prime = -2*z_val - np.exp(x)*y_val  # z' = -2z - e^x * y (из уравнения)
    
    # ───────────────────────────────────────────────────────────────────────
    # Возвращаем вектор производных
    # ───────────────────────────────────────────────────────────────────────
    return np.array([y_prime, z_prime])


# ═══════════════════════════════════════════════════════════════════════════
# ОЦЕНКА ПОГРЕШНОСТИ ПО МЕТОДУ РУНГЕ-РОМБЕРГА
# ═══════════════════════════════════════════════════════════════════════════

def runge_romberg_error(y_h: np.ndarray, y_2h: np.ndarray, p: int) -> float:
    """
    Оценка погрешности по методу Рунге-Ромберга
    
    Теория:
        Если метод имеет порядок точности p, то погрешность:
        ε(h) ≈ C * h^p
        
        При уменьшении шага в 2 раза:
        ε(h/2) ≈ C * (h/2)^p = ε(h) / 2^p
        
        Отсюда:
        ε(h) ≈ |y_h - y_{h/2}| / (2^p - 1)
    
    Параметры:
        y_h: решение с шагом h
        y_2h: решение с шагом 2h (в той же точке)
        p: порядок метода (1 для Эйлера, 4 для РК4 и Адамса)
    
    Возвращает:
        Оценку погрешности решения с шагом h
    
    Пример:
        Для РК4 (p=4):
        R_h = |y_h - y_2h| / (2^4 - 1) = |y_h - y_2h| / 15
    """
    
    # ───────────────────────────────────────────────────────────────────────
    # Вычисляем разность решений
    # ───────────────────────────────────────────────────────────────────────
    difference = np.abs(y_h - y_2h)
    
    # ───────────────────────────────────────────────────────────────────────
    # Применяем формулу Рунге-Ромберга
    # ───────────────────────────────────────────────────────────────────────
    # Знаменатель: 2^p - 1
    # Для p=1 (Эйлер): 2^1 - 1 = 1
    # Для p=4 (РК4, Адамс): 2^4 - 1 = 15
    denominator = 2**p - 1
    
    # Оценка погрешности
    error_estimate = difference / denominator
    
    return error_estimate


