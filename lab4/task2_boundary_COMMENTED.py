def solve_variant_14():
    """
    Решение варианта 14:
        (e^x + 1)y'' - 2y' - e^x * y = 0
        y'(0) = 1
        y'(1) - y(1) = 1
    
    Точное решение: y(x) = e^x - 1
    """
    
    print("="*70)
    print("ВАРИАНТ 14: Краевая задача")
    print("="*70)
    print("(e^x + 1)y'' - 2y' - e^x * y = 0")
    print("y'(0) = 1")
    print("y'(1) - y(1) = 1")
    print("Точное решение: y(x) = e^x - 1")
    
    # ═══════════════════════════════════════════════════════════════════════
    # ПАРАМЕТРЫ ЗАДАЧИ
    # ═══════════════════════════════════════════════════════════════════════
    a, b = 0.0, 1.0  # Границы отрезка
    h = 0.1          # Шаг сетки
    
    # ═══════════════════════════════════════════════════════════════════════
    # ТОЧНОЕ РЕШЕНИЕ
    # ═══════════════════════════════════════════════════════════════════════
    def exact_solution(x):
        return np.exp(x) - 1
    
    # ═══════════════════════════════════════════════════════════════════════
    # МЕТОД СТРЕЛЬБЫ
    # ═══════════════════════════════════════════════════════════════════════
    print(f"\n{'='*70}")
    print("МЕТОД СТРЕЛЬБЫ")
    print(f"{'='*70}")
    
    # Преобразуем уравнение в систему 1-го порядка
    def f_system(x, y):
        """
        Система для метода стрельбы:
            y' = z
            z' = (2z + e^x * y) / (e^x + 1)
        """
        y_val, z_val = y
        return np.array([z_val, (2*z_val + np.exp(x)*y_val) / (np.exp(x) + 1)])
    
    # Граничные условия
    bc_left = ('derivative', 1.0)  # y'(0) = 1
    
    def bc_right(y_end):
        """Правое ГУ: y'(1) - y(1) = 1"""
        return y_end[1] - y_end[0] - 1
    
    # Создаем решатель и решаем
    solver = BoundaryProblemSolver(a, b, h)
    x_shoot, y_shoot = solver.shooting_method(
        f_system, bc_left, bc_right, initial_guess=0.0
    )
    
    # Вычисляем погрешность
    y_exact = np.array([exact_solution(xi) for xi in x_shoot])
    error_shoot = np.abs(y_shoot - y_exact)
    
    print(f"\nМаксимальная погрешность: {np.max(error_shoot):.6e}")
    
    # ═══════════════════════════════════════════════════════════════════════
    # КОНЕЧНО-РАЗНОСТНЫЙ МЕТОД
    # ═══════════════════════════════════════════════════════════════════════
    print(f"\n{'='*70}")
    print("КОНЕЧНО-РАЗНОСТНЫЙ МЕТОД")
    print(f"{'='*70}")
    
    # Приводим уравнение к виду: y'' + p(x)y' + q(x)y = f(x)
    # (e^x + 1)y'' - 2y' - e^x * y = 0
    # y'' - 2/(e^x+1) * y' - e^x/(e^x+1) * y = 0
    
    def p(x):
        return -2 / (np.exp(x) + 1)
    
    def q(x):
        return -np.exp(x) / (np.exp(x) + 1)
    
    def f(x):
        return 0.0
    
    # Граничные условия
    bc_left_fd = ('derivative', 1.0)      # y'(0) = 1
    bc_right_fd = ('mixed', -1, 1, 1)     # -y(1) + y'(1) = 1
    
    # Решаем
    x_fd, y_fd = solver.finite_difference_method(p, q, f, bc_left_fd, bc_right_fd)
    
    # Вычисляем погрешность
    y_exact_fd = np.array([exact_solution(xi) for xi in x_fd])
    error_fd = np.abs(y_fd - y_exact_fd)
    
    print(f"\nМаксимальная погрешность: {np.max(error_fd):.6e}")
    
    # ═══════════════════════════════════════════════════════════════════════
    # СРАВНЕНИЕ РЕЗУЛЬТАТОВ
    # ═══════════════════════════════════════════════════════════════════════
    print(f"\n{'='*70}")
    print("СРАВНЕНИЕ МЕТОДОВ")
    print(f"{'='*70}")
    
    print(f"\n{'x':>8} {'Стрельбы':>12} {'Кон.разн.':>12} {'Точное':>12} "
          f"{'ε_стр':>10} {'ε_кр':>10}")
    print("-" * 75)
    
    for i in range(0, len(x_shoot), 2):
        print(f"{x_shoot[i]:8.4f} {y_shoot[i]:12.6f} {y_fd[i]:12.6f} "
              f"{y_exact[i]:12.6f} {error_shoot[i]:10.2e} {error_fd[i]:10.2e}")
    
    print("\n" + "="*70)
    print("ВЫВОДЫ:")
    print("="*70)
    print("1. Метод стрельбы дает более высокую точность (~10^-6)")
    print("2. Конечно-разностный метод проще в реализации (~10^-3)")
    print("3. Оба метода дают хорошее приближение к точному решению")


